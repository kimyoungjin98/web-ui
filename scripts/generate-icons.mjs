import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { getIconData, iconToSVG, replaceIDs } from "@iconify/utils";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDirectory, "..");
const manifestPath = resolve(
  packageRoot,
  "src/components/icon-manifest.ts",
);
const outputPath = resolve(
  packageRoot,
  "src/components/icon-data.generated.ts",
);

const collectionLoaders = {
  boxicons: () => import("@iconify-json/boxicons"),
  devicon: () => import("@iconify-json/devicon"),
  el: () => import("@iconify-json/el"),
  "eos-icons": () => import("@iconify-json/eos-icons"),
  flowbite: () => import("@iconify-json/flowbite"),
  gridicons: () => import("@iconify-json/gridicons"),
  ic: () => import("@iconify-json/ic"),
  lucide: () => import("@iconify-json/lucide"),
  "material-symbols": () => import("@iconify-json/material-symbols"),
  "material-symbols-light": () =>
    import("@iconify-json/material-symbols-light"),
  mdi: () => import("@iconify-json/mdi"),
  "qlementine-icons": () => import("@iconify-json/qlementine-icons"),
  selfhst: () => import("@iconify-json/selfhst"),
  "simple-icons": () => import("@iconify-json/simple-icons"),
  "skill-icons": () => import("@iconify-json/skill-icons"),
  "vscode-icons": () => import("@iconify-json/vscode-icons"),
};

// Monochrome brand marks that previously requested a fixed color from the
// Iconify API keep that official brand color in the generated SVG data.
const fixedColors = {
  "simple-icons:naver": "#03C75A",
  "simple-icons:notion": "#191919",
};

const iconNamePattern = new RegExp(
  `(?<![a-z0-9-])(?:${Object.keys(collectionLoaders)
    .sort((a, b) => b.length - a.length)
    .join("|")}):[a-z0-9][a-z0-9-]*(?![a-z0-9-])`,
  "g",
);

async function readIconManifest() {
  const source = await readFile(manifestPath, "utf8");
  const matches = [...source.matchAll(iconNamePattern)].map(
    (match) => match[0],
  );
  const names = [...new Set(matches)].sort();

  if (names.length === 0) {
    throw new Error(`No icon names were found in ${manifestPath}`);
  }

  if (names.length !== matches.length) {
    throw new Error(`Duplicate icon names were found in ${manifestPath}`);
  }

  return names;
}

async function generateIconData(names) {
  const collections = new Map();
  const entries = [];

  for (const name of names) {
    const [prefix, iconName] = name.split(":");
    let collection = collections.get(prefix);

    if (!collection) {
      const module = await collectionLoaders[prefix]();
      collection = module.icons;
      collections.set(prefix, collection);
    }

    const data = getIconData(collection, iconName);
    if (!data) {
      throw new Error(
        `Icon \"${name}\" was not found in @iconify-json/${prefix}`,
      );
    }

    const rendered = iconToSVG(data, { height: "auto" });
    let body = replaceIDs(rendered.body);
    const fixedColor = fixedColors[name];
    if (fixedColor) body = body.replaceAll("currentColor", fixedColor);

    entries.push(
      `  ${JSON.stringify(name)}: { body: ${JSON.stringify(body)}, viewBox: ${JSON.stringify(
        rendered.attributes.viewBox,
      )} },`,
    );
  }

  return entries;
}

const iconNames = await readIconManifest();
const entries = await generateIconData(iconNames);
const contents = `// This file is generated by packages/ui/scripts/generate-icons.mjs.
// Update icon-manifest.ts, then run \`pnpm --filter @repo/ui icons:generate\`.

import type { IconName } from "./icon-manifest";

type IconDefinition = {
  body: string;
  viewBox: string;
};

export const iconData = {
${entries.join("\n")}
} as const satisfies Record<IconName, IconDefinition>;
`;

await writeFile(outputPath, contents);
console.log(
  `Generated ${iconNames.length} local icons in ${relative(packageRoot, outputPath)}`,
);
