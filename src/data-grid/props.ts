  showToolbar?: boolean;
  pagination?: boolean;
  rowClassName?: (row: T, index: number) => string;
  onPageChange?: (page: number) => void;
  onPageSizeChange?: (pageSize: number) => void;
  onSortChange?: (sort: DataGridSort) => void;
  onSearchChange?: (search: string) => void;
